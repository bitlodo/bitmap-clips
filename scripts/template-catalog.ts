import {readdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';

/** Discover exported projects without requiring handwritten imports or registration. */
export async function generateTemplateCatalog(root=resolve(import.meta.dir,'../src/project-templates')){
 const files=(await readdir(resolve(root,'projects'))).filter(file=>file.endsWith('.json')).sort();
 const lines=['// Generated by scripts/template-catalog.ts. Edit project JSON files instead.',"import {defineExportedProjectTemplate} from './exported-project';"];
 for(const [index,file] of files.entries()){
  const document=JSON.parse(await readFile(resolve(root,'projects',file),'utf8'));
  if(typeof document.name!=='string'||!document.name.trim())throw Error(`Template ${file} needs a nonempty project name.`);
  lines.push(`import project${index} from ${JSON.stringify('./projects/'+file)};`);
 }
 lines.push('export const exportedProjectTemplates=[',...files.map((file,index)=>` defineExportedProjectTemplate(${JSON.stringify(file.slice(0,-5))},project${index}),`),'];','');
 const output=resolve(root,'catalog.generated.ts'),source=lines.join('\n');
 let previous='';try{previous=await readFile(output,'utf8');}catch(error){if((error as NodeJS.ErrnoException).code!=='ENOENT')throw error;}
 if(previous!==source)await writeFile(output,source);
}
if(import.meta.main)await generateTemplateCatalog();
